// Build the RPM via the electron-installer-redhat API so we can pass a custom
// desktop template (StartupWMClass) — the CLI doesn't expose it. Run after
// electron-packager has produced builds/pikvm-desktop-linux-x64.
import installer from "electron-installer-redhat";
import { mkdirSync, writeFileSync } from "fs";
import { resolve } from "path";

const root = resolve(import.meta.dirname, "..");

/* Stop rpmbuild rewriting the bundled Python runtime.
 *
 * Fedora's brp-mangle-shebangs runs over everything being packaged and rewrites
 * `#!/usr/bin/env python3` to `#!/usr/bin/python3`. Harmless for a normal
 * package; for resources/agent/runtime it is the exact bug the bundled runtime
 * exists to fix, silently repointing hundreds of files at an interpreter that is
 * the user's, not ours, and need not exist at all. It then failed the build
 * outright on CPython's own encodings/rot_13.py, whose `#!/usr/bin/env python`
 * it calls ambiguous.
 *
 * electron-installer-redhat hardcodes its spec template and spawns rpmbuild
 * itself, so there is no option to pass and nowhere to put a %global. rpm reads
 * ~/.rpmmacros, so HOME is pointed at a directory holding exactly that file, for
 * this process only. Not the user's ~/.rpmmacros — writing to that would be
 * changing their machine's configuration to build one package.
 *
 * The strip scripts go for a harder reason: they do not just rewrite the bundled
 * interpreter, they BREAK it. A packaged python3 came out of the first working
 * build saying
 *
 *     no version information available (required by .../bin/python3)
 *     symbol lookup error: undefined symbol: , version
 *
 * on every invocation, while the identical binary ran fine in agent/runtime a
 * moment before. python-build-standalone ships a statically linked libpython
 * whose symbol versioning does not survive rpmbuild's strip, and nothing in the
 * build fails when it happens — the package builds clean and the agent is dead
 * on the installed machine, which is the failure mode this whole change exists
 * to end. Found by extracting the RPM and running the binary out of it.
 *
 * Electron's own binaries stop being stripped as a side effect. They arrive
 * prebuilt and already stripped, so the cost is nil.
 *
 * rpath checks still run (QA_RPATHS below keeps them non-fatal), and everything
 * else about how the package is built is unchanged. */
const rpmHome = resolve(root, "builds/.rpm-macros");
mkdirSync(rpmHome, { recursive: true });
writeFileSync(
    resolve(rpmHome, ".rpmmacros"),
    [
        "# Generated by scripts/make-rpm.mjs. See the comment there.",
        "%__brp_mangle_shebangs %{nil}",
        "%__brp_strip %{nil}",
        "%__brp_strip_lto %{nil}",
        "%__brp_strip_comment_note %{nil}",
        "%__brp_strip_static_archive %{nil}",
        "",
    ].join("\n"),
    "utf8",
);
process.env.HOME = rpmHome;

// whisper.cpp's prebuilt .so/binaries carry RPATHs pointing at their compile-time
// build dir, which rpmbuild's check-rpaths treats as fatal (invalid + empty runpath).
// They're a non-issue for our shipping model (bundled native libs that load their
// own siblings), so tell rpmbuild to allow them rather than fail the whole package.
// 0x1F = every check-rpaths bit (standard|invalid|...|empty). Inherited by rpmbuild.
process.env.QA_RPATHS = "0x001F";

await installer({
    src: resolve(root, "builds/pikvm-desktop-linux-x64/"),
    dest: resolve(root, "builds/rpm/"),
    arch: "x86_64",
    name: "pikvm-desktop",
    productName: "PiKVM Desktop",
    genericName: "Remote Desktop",
    bin: "pikvm-desktop",
    icon: resolve(root, "src/assets/icon.png"),
    desktopTemplate: resolve(root, "build/desktop.ejs"),
});

console.log("RPM built (with StartupWMClass).");
